nombre_Empleado = input("Ingrese el nombre del empleado: ")
Num_Horas = float(input("Ingrese el número de horas trabajadas: "))
valor_Hora = float(input("Ingrese el valor de la hora trabajada: "))

salario = Num_Horas * valor_Hora

print("Nombre del empleado: ", nombre_Empleado)
print("Número de horas trabajadas: ", Num_Horas)
print("Valor de la hora trabajada: ", valor_Hora)
print("El salario del empleado es: ", salario)